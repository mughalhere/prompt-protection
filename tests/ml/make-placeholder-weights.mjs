// Writes the PLACEHOLDER src/ml/weights.ts: seeded-LCG int8 weights with an inert
// bias/scale so decoding is exercised end-to-end before a real model ships.
// Usage: node tests/ml/make-placeholder-weights.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const BUCKETS = 65_536;
const SEED = 0x9e3779b9;

let x = SEED >>> 0;
const bytes = new Uint8Array(BUCKETS);
for (let i = 0; i < BUCKETS; i++) {
  x = (Math.imul(x, 1_664_525) + 1_013_904_223) >>> 0;
  bytes[i] = x >>> 24;
}

const sha256 = createHash('sha256').update(bytes).digest('hex');
const b64 = Buffer.from(bytes).toString('base64');
const bias = Math.fround(Math.log(0.02 / 0.98));

const out = `// src/ml/weights.ts, PLACEHOLDER generated by tests/ml/make-placeholder-weights.mjs.
// Replaced by training/export.py (GENERATED, do not edit). Seeded-LCG int8 weights
// with an inert intercept: sigmoid(bias) ≈ 0.02 and scale 1e-4 keep p ≈ 0.02 everywhere.
export const MODEL_META = {
  version: '0.0.0-placeholder',
  buckets: ${BUCKETS},
  storage: 'dense-int8',
  ngramChar: [3, 5],
  ngramWord: [1, 2],
  maxChars: 4000,
  scale: 0.0001,
  bias: ${bias},
  norm: 'l2-binary',
  thresholds: { flag: 0.6, block: 0.9, benign: 0.1 },
  trainedAt: '1970-01-01T00:00:00Z',
  sha256: '${sha256}',
} as const;
export const WEIGHTS_B64 =
  '${b64}';
`;

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', '..', 'src', 'ml', 'weights.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: ${BUCKETS} buckets, sha256 ${sha256}, bias ${bias}`);
